/** Regenerates settled-snapshot.ts from the current simulation (see settled.ts). */
import fs from "node:fs";
import { fileURLToPath } from "node:url";
import { computeSilkSettledState } from "./settled";

const state = computeSilkSettledState();
const encode = (values: readonly number[]) =>
  Buffer.from(new Float64Array(values).buffer).toString("base64");
const target = fileURLToPath(new URL("./settled-snapshot.ts", import.meta.url));
fs.writeFileSync(
  target,
  `// Generated by settled.generate.ts. Do not edit.\nexport const SILK_SETTLED_SNAPSHOT = {\n` +
    `  time: ${state.time},\n  seed: ${JSON.stringify(state.seed)} as [number, number, number] | null,\n` +
    `  pos: "${encode(state.pos)}",\n  prev: "${encode(state.prev)}",\n};\n`,
);
console.log(`wrote ${target}`);
