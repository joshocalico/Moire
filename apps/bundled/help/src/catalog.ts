export function searchHelp(query: string): HelpTopic[] {
  const needle = query.trim().toLocaleLowerCase();
  return HELP_TOPICS.filter((topic) =>
    `${topic.title} ${topic.category} ${topic.body} ${topic.shortcuts.map((shortcut) => `${shortcut.keys} ${shortcut.action}`).join(" ")}`
      .toLocaleLowerCase()
      .includes(needle),
  );
}
